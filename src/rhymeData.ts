/**
 * Recommends the best poetic rhyme letter based on the selected purpose and text description.
 */
export function suggestBestRhymeLetter(purpose: string, descriptionText: string): { letter: string; reason: string } {
  const normPurpose = purpose.toLowerCase();
  const text = (descriptionText || '').toLowerCase();

  // Rules based on Arabic classical poetry phonetics
  if (normPurpose.includes('madah') || normPurpose.includes('مدح') || normPurpose.includes('ثن') || text.includes('مدح') || text.includes('رسول')) {
    return {
      letter: 'ر',
      reason: 'الرَّاء حرف تكراري فخم ذو جرس مهيب ورنين باهر، هو سيد القوافي التاريخية في المعلقات والمدائح الكبرى والقصائد النبوية العظيمة.'
    };
  }
  if (normPurpose.includes('ghazal') || normPurpose.includes('غزل') || normPurpose.includes('وجد') || text.includes('حب') || text.includes('عشق') || text.includes('شوق')) {
    return {
      letter: 'ل',
      reason: 'اللاَّم حرف رقيق شديد السلاسة ذو جرس عذب منساب يترجم دقات الوجدان وحنين العاشقين بكفاءة لغوية فائقة.'
    };
  }
  if (normPurpose.includes('ratha') || normPurpose.includes('رثاء') || normPurpose.includes('حزن') || text.includes('موت') || text.includes('فقد') || text.includes('قبر')) {
    return {
      letter: 'م',
      reason: 'المِيم حرف شفوي تنهدي شجي يغلق الشفتين بوقار وعمق، يفيض بآهات الفقد ومصارع الفحول وجليل الرثاء العائلي والقومي.'
    };
  }
  if (normPurpose.includes('hikma') || normPurpose.includes('حكمة') || normPurpose.includes('زهد') || normPurpose.includes('تأمل') || text.includes('زمان') || text.includes('دهر')) {
    return {
      letter: 'د',
      reason: 'الدَّال حرف شديد وقور ذو رونق راسخ يدعو للطمأنينة والتأمل، وهو الأنسب لصياغة الحكم السائرة وتجارب الحياة العميقة.'
    };
  }
  if (normPurpose.includes('fakhr') || normPurpose.includes('فخر') || normPurpose.includes('حماس') || text.includes('شجاع') || text.includes('حرب') || text.includes('جيش')) {
    return {
      letter: 'ق',
      reason: 'القَاف حرف لهوي مجهور شديد الانفجار، صلب الوقع يصك الأسماع، ملائم تماماً لقصائد الإقدام والفروسية والهتاف الوطني الهادر.'
    };
  }
  if (text.includes('مطر') || text.includes('ربيع') || text.includes('طبيعة') || text.includes('ورد')) {
    return {
      letter: 'ف',
      reason: 'الفَاء حرف همس رخو منساب بالندى، كأنه نسيم رقيق يعبر عن جمال الربيع وتفتح البساتين وحبات المطر برقة متناهية.'
    };
  }

  // Default suggestions based on ease of rhyme
  const easyLetters = [
    { letter: 'ن', reason: 'النُّون حرف غنة شجي وممتد وله رواج هائل في النظم لمرونته وسهولة تفتق المعاني عليه في كافة البحور.' },
    { letter: 'د', reason: 'الدَّال حرف عذب وقور يمنح نهاية الأبيات جرساً ثابتاً ومحبباً لدى السامع ويسهل سبكه وصياغته.' },
    { letter: 'ر', reason: 'الرَّاء سيد القوافي الكلاسيكية، يثبت تماسك الأبيات ويعطي جلالاً وفخامة استثنائية لإيقاع القصيدة.' }
  ];
  return easyLetters[Math.floor(Math.random() * easyLetters.length)];
}
